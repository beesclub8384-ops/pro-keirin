-- 1. prize_money_standards: 성적상금 기준표 (등급·착순·일차별)
CREATE TABLE IF NOT EXISTS prize_money_standards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  year SMALLINT NOT NULL,
  race_type TEXT NOT NULL,        -- '일반','대상GII','왕중왕GI','그랑프리GP'
  day SMALLINT NOT NULL,          -- 일차 (1,2,3)
  grade TEXT NOT NULL,            -- '선발','우수','특선' 등
  rank SMALLINT NOT NULL,         -- 착순
  amount INTEGER NOT NULL         -- 상금액 (천원 단위, ×1000 해서 사용)
);

-- 2. prize_allowances: 출전상금/안전상금/출전준비금 기준표
CREATE TABLE IF NOT EXISTS prize_allowances (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  year SMALLINT NOT NULL,
  grade TEXT NOT NULL,
  entry_fee_per_day INTEGER,      -- 출전상금 1일당 (원)
  safety_fee_per_day INTEGER,     -- 안전상금 1일당 (원)
  prep_fee INTEGER,               -- 출전준비금 회차당 (원)
  note TEXT
);
COMMENT ON TABLE prize_allowances IS '연도별 출전상금/안전상금/출전준비금 기준표. 협약서 기반 수동 입력.';
COMMENT ON COLUMN prize_allowances.entry_fee_per_day IS '출전상금 1일당 금액 (원)';
COMMENT ON COLUMN prize_allowances.safety_fee_per_day IS '안전상금 1일당 금액 (원)';
COMMENT ON COLUMN prize_allowances.prep_fee IS '출전 준비금 회차당 금액 (원)';

-- 3. special_rounds: 특별경주 회차 목록
CREATE TABLE IF NOT EXISTS special_rounds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  year SMALLINT NOT NULL,
  round SMALLINT NOT NULL,
  race_type TEXT NOT NULL,        -- '대상GII','왕중왕GI','그랑프리GP'
  source TEXT NOT NULL,           -- 'schedule','auto','manual'
  note TEXT,
  grade_scope TEXT NOT NULL DEFAULT '특선'
    CHECK (grade_scope IN ('전등급', '특선')),
  UNIQUE (year, round)
);
COMMENT ON TABLE special_rounds IS '연도별 특별경주(대상GII/왕중왕GI/그랑프리GP) 회차 목록';
COMMENT ON COLUMN special_rounds.grade_scope IS '전등급: 선발/우수/특선 모두 해당 대회 상금. 특선: 특선만 대회 상금, 우수/선발은 일반경륜 상금';

-- 4. four_day_rounds: 4일 경륜 회차 목록
CREATE TABLE IF NOT EXISTS four_day_rounds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  year SMALLINT NOT NULL,
  round SMALLINT NOT NULL,
  note TEXT
);
COMMENT ON TABLE four_day_rounds IS '4일 경륜 회차 목록. 3일차=2일차 상금, 4일차=3일차 상금 적용';


