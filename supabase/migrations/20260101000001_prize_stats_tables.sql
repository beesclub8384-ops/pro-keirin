-- ============================================================
-- 5. fn_prize_stats_full() 함수
-- ============================================================

CREATE OR REPLACE FUNCTION fn_prize_stats_full()
RETURNS TABLE (
  year SMALLINT,
  performance_prize BIGINT,
  entry_prize BIGINT,
  safety_prize BIGINT,
  prep_prize BIGINT,
  total_prize BIGINT,
  unmatched_count BIGINT,
  has_performance_data BOOLEAN
) LANGUAGE sql STABLE AS $$
WITH 유효일차 AS (
  SELECT rc.id,
    CASE
      WHEN fdr.id IS NOT NULL AND rc.day = 3 THEN 2
      WHEN fdr.id IS NOT NULL AND rc.day = 4 THEN 3
      ELSE rc.day
    END as effective_day
  FROM races rc
  LEFT JOIN four_day_rounds fdr ON fdr.year = rc.year AND fdr.round = rc.round
  WHERE rc.year BETWEEN 2015 AND 2025
),
경주유형 AS (
  -- 경주별로 어떤 prize_money_standards race_type을 써야 하는지 결정
  SELECT
    rc.id as race_id,
    rc.year,
    rc.race_no,
    dcr.id as dcr_id,
    dcr.race_type as grade,
    ed.effective_day,
    CASE
      WHEN sr.id IS NULL THEN '일반'
      WHEN sr.race_type = '그랑프리GP' THEN '그랑프리GP'
      WHEN sr.race_type = '왕중왕GI' THEN '왕중왕GI'
      WHEN sr.race_type = '대상GII'
        AND dcr.race_type IN ('특선','특선준결','특선결승') THEN '대상GII'
      WHEN sr.race_type = '대상GII' AND sr.grade_scope = '전등급'
        AND dcr.race_type IN ('우수','우수준결','우수결승','선발','선발준결','선발결승') THEN '왕중왕GI'
      WHEN sr.race_type = '대상GII' AND sr.grade_scope = '특선'
        AND dcr.race_type IN ('우수','우수준결','우수결승','선발','선발준결','선발결승') THEN '일반'
      ELSE '일반'
    END as pms_race_type
  FROM races rc
  JOIN 유효일차 ed ON ed.id = rc.id
  JOIN decision_card_pages dcp ON dcp.year = rc.year AND dcp.round = rc.round AND dcp.day = rc.day
  JOIN decision_card_races dcr ON dcr.page_id = dcp.id AND dcr.race_no = rc.race_no
  LEFT JOIN special_rounds sr ON sr.year = rc.year AND sr.round = rc.round
  WHERE dcr.race_type IN (
    '선발','선발결승','선발준결','우수','우수결승','우수준결',
    '특선','특선결승','특선준결','그랑프리결승','준결','특우'
  )
),
성적상금 AS (
  SELECT
    rc.year,
    SUM(pms.amount) * 1000 as 성적상금_총액,
    COUNT(CASE WHEN pms.amount IS NULL THEN 1 END) as 미매핑건수
  FROM races rc
  JOIN race_results rr ON rr.race_id = rc.id
  JOIN 경주유형 cu ON cu.race_id = rc.id AND cu.race_no = rc.race_no
  LEFT JOIN prize_money_standards pms ON
    pms.year = rc.year
    AND pms.race_type = cu.pms_race_type
    AND pms.day = cu.effective_day
    AND pms.grade = cu.grade
    AND pms.rank = rr.rank
  WHERE rc.year BETWEEN 2015 AND 2025
    AND rr.rank IS NOT NULL
  GROUP BY rc.year
),
기타상금 AS (
  SELECT
    rc.year,
    COUNT(*) * 300000 as 출전상금_총액,
    COUNT(CASE WHEN rr.withdrawal = '-' THEN 1 END) * pa.safety_fee_per_day as 안전상금_총액,
    COUNT(DISTINCT rr.name || '-' || CAST(rc.round AS TEXT)) * 100000 as 출전준비금_총액
  FROM races rc
  JOIN race_results rr ON rr.race_id = rc.id
  JOIN prize_allowances pa ON pa.year = rc.year AND pa.grade = '특선'
  WHERE rc.year BETWEEN 2015 AND 2025
  GROUP BY rc.year, pa.safety_fee_per_day
)
SELECT
  s.year::SMALLINT,
  COALESCE(s.성적상금_총액, 0)::BIGINT as performance_prize,
  k.출전상금_총액::BIGINT as entry_prize,
  k.안전상금_총액::BIGINT as safety_prize,
  k.출전준비금_총액::BIGINT as prep_prize,
  (COALESCE(s.성적상금_총액, 0) + k.출전상금_총액 + k.안전상금_총액 + k.출전준비금_총액)::BIGINT as total_prize,
  s.미매핑건수::BIGINT as unmatched_count,
  (s.미매핑건수 < 500) as has_performance_data
FROM 성적상금 s
JOIN 기타상금 k ON k.year = s.year
ORDER BY s.year;
$$;
